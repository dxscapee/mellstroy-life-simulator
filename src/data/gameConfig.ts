import Decimal from 'break_infinity.js';

/**
 * Весь тюнинг экономики и UI-констант — здесь. Код игры не должен
 * содержать «магических чисел»: всё берётся из этого конфига.
 *
 * Экономика двух потоков:
 *   A (активный, за тап)  = moneyPerTap  * (1 + Σ aWeight * level * tierFactor)
 *   P (пассивный, /сек)   = passiveBase  * (1 + Σ pWeight * level * tierFactor)
 * Вклад не купленного объекта (level 0) равен нулю — флаг владения 0/1
 * получается сам: пока level = 0, объект в сумму не входит.
 *
 * Эволюция объекта: каждые levelsPerTier покупок объект «апгрейдится» —
 * новая моделька/название (tierNames), а вклад уровня умножается на
 * weightMultiplierPerTier, но сам процент за уровень слегка падает:
 * эффективный множитель тира = (weightMultiplierPerTier * weightDecayPerTier) ^ tier.
 */
export const gameConfig = {
  /** Стартовый баланс нового игрока. */
  startingMoney: new Decimal(50),

  /** База АКТИВНОГО потока: доход за один тап «голого» игрока. */
  moneyPerTap: new Decimal(2),
  /** База ПАССИВНОГО потока: доход в секунду «голого» игрока. */
  passiveBase: new Decimal(1),

  /** Эволюция: каждые N уровней объект переходит на следующую стадию (прогресс-бар карточки). */
  tiers: {
    levelsPerTier: 10,
    /** Вклад уровня умножается на это за каждый тир (стадия 2 = x2 к «сырому» вкладу). */
    weightMultiplierPerTier: 2,
    /** Процент за уровень при этом слегка падает: вес × 0.9^tier (ослабление экспоненты). */
    weightDecayPerTier: 0.9,
  },

  /** Мета-прогресс подписчиков: шкала заполняется пассивом и кликами, награда — по клику на чип. */
  subscribers: {
    /** Раз в N секунд прилетает пассивДоход×N подписчиков. */
    addIntervalSec: 5,
    /** Каждый N-й клик даёт подписчиков (величина = доход за этот клик). 1 = за каждый клик. */
    clickBonusEvery: 1,
    /** Цель цикла = goalMult × (доход за клик В МОМЕНТ старта цикла); после claim:
     *  новая цель = старая + goalMult × (тап на момент клейма). Рост тапа ЦЕЛЬ не меняет. */
    goalMult: 500,
    /** Награда за заполнение шкалы = rewardMult × (доход за клик НА МОМЕНТ клейма). */
    rewardMult: 500,
  },

  /** Автосейв каждые N секунд. */
  autoSaveIntervalSec: 10,

  /** Офлайн-доход: максимум начисляем при возврате. */
  offline: {
    /** Дольше этого времени офлайн-доход не капает. */
    maxSeconds: 8 * 60 * 60, // 8 часов
    /** Игрок получает такой процент от онлайн-дохода за время отсутствия. */
    efficiency: 0.5, // 50%
    /** Меньше этого порога — модалку не показываем, тихо начисляем. */
    minSecondsToShow: 60,
  },

  /** Дебаг-ускорение времени применяется только в dev-сборке. */
  debug: {
    timeScales: [1, 5, 10] as const,
  },
} as const;

export type GameConfig = typeof gameConfig;
