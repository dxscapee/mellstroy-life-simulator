/**
 * Стадии МИРА — третье измерение прогресса (помимо уровней объектов и подписчиков).
 *
 * Единая лог-шкала: мир живёт в «периодах» по WORLD_EXP_STEP порядков totalEarned
 * (всё заработанное за жизнь сейва: покупки + накопления + офлайн).
 * Экономика экспоненциальна → пороги по степеням дают игроку равномерный темп.
 *
 * Разделение слоёв (решение владельца):
 *   растительность (средний слой) — меняется КАЖДЫЙ период (12 раз за игру);
 *   задний фон (задний слой)      — каждый ВТОРОЙ период (6 эпох, «редкое событие»).
 * Итого: bg0+veg0 → bg0+veg1 → bg1+veg2 → bg1+veg3 → … → bg5+veg10 → bg5+veg11.
 *
 * Текстуры позже подгружаются списком файлов; пока ассетов нет, WorldLayer
 * рисует плейсхолдеры. Имена стадий — в чипе эпохи (HUD) и в галерее.
 */

/** Ширина периода по totalEarned: период N = totalEarned >= 10^(STEP*N). */
export const WORLD_EXP_STEP = 2.5;
/** Всего периодов лог-шкалы (растительность). 6 эпох фона = 12 периодов. */
export const WORLD_PERIODS = 12;

/** Имена ПЕРИОДОВ растительности (12): тост на смене + галерея. */
export const WORLD_VEGETATION_NAMES: readonly string[] = [
  'Заросший пустырь', 'Редкий кустарник', 'Молодые посадки', 'Сквер',
  'Роща', 'Парк', 'Аллеи', 'Сад у дома',
  'Городские скверы', 'Висячие сады', 'Зелёный квартал', 'Эко-район',
];

/** Имена ЭПОХ ЗАДНЕГО ФОНА (6): чип HUD, тост на смене, галерея. */
export const WORLD_ERA_NAMES: readonly string[] = [
  'Пустошь', 'Окраина', 'Предместье', 'Городок', 'Мегаполис', 'Мегаструктура',
];

/** Файл заднего фона эпохи: WorldLayer сам решает, video это или картинка. */
export const worldEraBackground = (era: number): string => `assets/world/bg_${era}`;
/** Ключ фазы растительности: по нему WorldLayer находит/строит плейсхолдер. */
export const worldVegetationKey = (period: number): string => `veg_${period}`;
